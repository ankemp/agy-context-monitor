import json
import os
import subprocess
import sys
from pathlib import Path
import pytest


def test_default_settings_disable_artifacts(tmp_path, monkeypatch):
    from context_monitor.settings import should_generate_artifacts, get_settings

    settings_file = tmp_path / "context_monitor_settings.json"
    monkeypatch.setenv("AGY_SETTINGS_PATH", str(settings_file))
    monkeypatch.delenv("CONTEXT_MONITOR_GENERATE_ARTIFACTS", raising=False)

    settings = get_settings()
    assert settings.get("generate_artifacts") is False
    assert should_generate_artifacts() is False


def test_file_toggle_enables_and_disables_artifacts(tmp_path, monkeypatch):
    from context_monitor.settings import should_generate_artifacts, save_settings, get_settings

    settings_file = tmp_path / "context_monitor_settings.json"
    monkeypatch.setenv("AGY_SETTINGS_PATH", str(settings_file))
    monkeypatch.delenv("CONTEXT_MONITOR_GENERATE_ARTIFACTS", raising=False)

    save_settings({"generate_artifacts": True})
    assert settings_file.exists()
    assert get_settings()["generate_artifacts"] is True
    assert should_generate_artifacts() is True

    save_settings({"generate_artifacts": False})
    assert get_settings()["generate_artifacts"] is False
    assert should_generate_artifacts() is False


def test_env_override_takes_precedence(tmp_path, monkeypatch):
    from context_monitor.settings import should_generate_artifacts, save_settings

    settings_file = tmp_path / "context_monitor_settings.json"
    monkeypatch.setenv("AGY_SETTINGS_PATH", str(settings_file))

    # File says False, env says "1" -> True
    save_settings({"generate_artifacts": False})
    monkeypatch.setenv("CONTEXT_MONITOR_GENERATE_ARTIFACTS", "1")
    assert should_generate_artifacts() is True

    # File says True, env says "0" -> False
    save_settings({"generate_artifacts": True})
    monkeypatch.setenv("CONTEXT_MONITOR_GENERATE_ARTIFACTS", "0")
    assert should_generate_artifacts() is False

    # String "true" / "false"
    monkeypatch.setenv("CONTEXT_MONITOR_GENERATE_ARTIFACTS", "true")
    assert should_generate_artifacts() is True
    monkeypatch.setenv("CONTEXT_MONITOR_GENERATE_ARTIFACTS", "false")
    assert should_generate_artifacts() is False


def test_ingest_skips_artifacts_by_default(tmp_path):
    cid = "test-cid-default-off"
    brain_dir = tmp_path / ".gemini" / "antigravity" / "brain" / cid
    brain_dir.mkdir(parents=True)

    transcript_file = tmp_path / "transcript.jsonl"
    transcript_file.write_text(json.dumps({
        "step_index": 1,
        "source": "USER_EXPLICIT",
        "type": "USER_INPUT",
        "created_at": "2026-10-13T10:00:00Z",
        "content": "Hello"
    }) + "\n")

    settings_file = tmp_path / "context_monitor_settings.json"
    env = os.environ.copy()
    env["HOME"] = str(tmp_path)
    env["AGY_SETTINGS_PATH"] = str(settings_file)
    env["PYTHONPATH"] = "src:."
    env.pop("CONTEXT_MONITOR_GENERATE_ARTIFACTS", None)

    input_payload = {
        "conversationId": cid,
        "transcriptPath": str(transcript_file)
    }

    proc = subprocess.run(
        [sys.executable, "scripts/ingest.py"],
        input=json.dumps(input_payload),
        text=True,
        capture_output=True,
        env=env,
        cwd=Path.cwd()
    )
    assert proc.returncode == 0
    assert not (brain_dir / "context_usage.md").exists(), "context_usage.md must NOT be generated by default"
    assert not (brain_dir / "context_usage.html").exists(), "context_usage.html must NOT be generated by default"


